"""Build a synthetic protein+ligand PDB so receptor prep can be tested offline.

Makes a folded-ish polypeptide with RDKit, places a small-molecule ligand near
its centre of mass as HETATM, and adds waters and a sulfate so the cleaning
code has real junk to strip. Two chains, so chain selection is exercised too.

This is a software fixture. It is not a real protein and the geometry is not
physically meaningful.
"""

from __future__ import annotations

import os
import numpy as np
from rdkit import Chem, RDLogger
from rdkit.Chem import AllChem

RDLogger.DisableLog("rdApp.*")
HERE = os.path.dirname(os.path.abspath(__file__))

SEQ = "AGCVLSTYKDEFWHNQRIPM"  # 20 residues, all standard types


def build_peptide(seq: str, seed: int) -> Chem.Mol:
    mol = Chem.MolFromSequence(seq)
    if mol is None:
        raise RuntimeError("could not build peptide")
    mol = Chem.AddHs(mol)
    params = AllChem.ETKDGv3()
    params.randomSeed = seed
    params.useRandomCoords = True
    params.maxIterations = 2000
    if AllChem.EmbedMolecule(mol, params) != 0:
        # Last resort for a long chain: plain random-coordinate embedding
        if AllChem.EmbedMolecule(mol, randomSeed=seed, useRandomCoords=True) != 0:
            raise RuntimeError("could not embed peptide")
    try:
        AllChem.MMFFOptimizeMolecule(mol, maxIters=500)
    except ValueError:
        pass  # unminimised geometry is fine for a fixture
    return mol


def atom_lines(mol: Chem.Mol, chain: str, start_serial: int, record: str = "ATOM",
               resname_override: str | None = None, resseq_override: int | None = None,
               offset: np.ndarray | None = None) -> tuple[list[str], int]:
    conf = mol.GetConformer()
    lines = []
    serial = start_serial
    seen: dict[int, int] = {}
    for atom in mol.GetAtoms():
        if atom.GetSymbol() == "H":
            continue
        pos = np.array(list(conf.GetAtomPosition(atom.GetIdx())))
        if offset is not None:
            pos = pos + offset

        info = atom.GetPDBResidueInfo()
        if resname_override:
            resname, resseq, name = resname_override, (resseq_override or 1), atom.GetSymbol()
            name = f"{atom.GetSymbol()}{seen.get(0, 0) + 1}"
            seen[0] = seen.get(0, 0) + 1
        elif info is not None:
            resname = info.GetResidueName().strip()
            resseq = info.GetResidueNumber()
            name = info.GetName().strip()
        else:
            resname, resseq, name = "UNK", 1, atom.GetSymbol()

        element = atom.GetSymbol()
        lines.append(
            f"{record:<6}{serial:>5} {name:<4}{'':1}{resname:>3} {chain:1}{resseq:>4}{'':1}   "
            f"{pos[0]:>8.3f}{pos[1]:>8.3f}{pos[2]:>8.3f}{1.00:>6.2f}{25.00:>6.2f}          {element:>2}"
        )
        serial += 1
    return lines, serial


def main() -> None:
    out = os.path.join(HERE, "sample_receptor.pdb")

    pep_a = build_peptide(SEQ, seed=11)
    pep_b = build_peptide(SEQ, seed=23)

    lines = ["REMARK   SYNTHETIC FIXTURE -- not a real structure",
             "REMARK   generated by pharma-ops examples/make_sample_pdb.py"]

    la, serial = atom_lines(pep_a, "A", 1)
    lines += la

    # Chain B displaced so it is clearly a separate copy
    conf_a = pep_a.GetConformer()
    coords_a = np.array([list(conf_a.GetAtomPosition(i)) for i in range(pep_a.GetNumAtoms())])
    span = coords_a.max(axis=0) - coords_a.min(axis=0)
    lb, serial = atom_lines(pep_b, "B", serial, offset=np.array([span[0] + 12.0, 0.0, 0.0]))
    lines += lb

    # Ligand: an indazole-like fragment, placed at chain A's centroid
    lig = Chem.MolFromSmiles("CC(C)c1cc2c(N)ncnc2[nH]1")
    lig = Chem.AddHs(lig)
    p = AllChem.ETKDGv3()
    p.randomSeed = 5
    AllChem.EmbedMolecule(lig, p)
    AllChem.MMFFOptimizeMolecule(lig, maxIters=300)
    conf_l = lig.GetConformer()
    lig_coords = np.array([list(conf_l.GetAtomPosition(i)) for i in range(lig.GetNumAtoms())])
    target = coords_a.mean(axis=0)
    shift = target - lig_coords.mean(axis=0)
    ll, serial = atom_lines(lig, "A", serial, record="HETATM",
                            resname_override="LIG", resseq_override=900, offset=shift)
    lines += ll

    # Junk to be stripped: waters, a sulfate, a glycerol, a zinc
    rng = np.random.default_rng(3)
    junk = [("HOH", ["O"]), ("HOH", ["O"]), ("HOH", ["O"]), ("HOH", ["O"]),
            ("SO4", ["S", "O", "O", "O", "O"]),
            ("GOL", ["C", "C", "C", "O", "O", "O"]),
            ("ZN", ["ZN"])]
    resseq = 950
    for resname, elements in junk:
        base = target + rng.uniform(-18, 18, size=3)
        for k, el in enumerate(elements):
            pos = base + rng.uniform(-1.4, 1.4, size=3)
            lines.append(
                f"HETATM{serial:>5} {el:<4}{'':1}{resname:>3} {'A':1}{resseq:>4}{'':1}   "
                f"{pos[0]:>8.3f}{pos[1]:>8.3f}{pos[2]:>8.3f}{1.00:>6.2f}{40.00:>6.2f}          {el:>2}"
            )
            serial += 1
        resseq += 1

    lines += ["TER", "END"]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
